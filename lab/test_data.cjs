test('Rates are recomputed from counts, and the accepted histories add up', () => {
  for (const run of Object.values(D.hero)) for (const key of ['local', 'full']) {
    const row = run[key];
    near(row.probability, row.accepted / row.shots);
    // histories with a click at step 3 are indices 4..7
    const hits = row.history_probabilities.slice(4).reduce((a, b) => a + b, 0);
    near(hits, row.probability, 1e-12, `${run.run} ${key}`);
    near(row.history_probabilities.reduce((a, b) => a + b, 0), 1, 1e-12);
  }
});

test('Total-variation distances can be recomputed from the measured histories and the engine', () => {
  const model = E.makeModel();
  const marked = y => ((y >> 2) & 1) === 1;
  const exact = E.conditionalDistribution(E.historyProbabilities(model, 3), marked);
  for (const run of Object.values(D.hero)) for (const key of ['local', 'full']) {
    const row = run[key];
    const measured = E.conditionalDistribution(Float64Array.from(row.history_probabilities), marked);
    near(E.totalVariation(measured, exact), row.tv_to_exact, 1e-9, `${run.run} ${key} TV`);
  }
});

test('The ideal values stored with each measurement are what the engine computes', () => {
  const model = E.makeModel(), steer = E.steerFor(model, 3);
  const kinds = { local: 'memory+last-1', full: 'full' };
  for (const run of Object.values(D.hero)) for (const [key, reflection] of Object.entries(kinds)) {
    const ideal = E.amplifiedHistory(model, 3, { r: 1, reflection, steer });
    near(run[key].ideal_probability, ideal.hit, 1e-9, `${run.run} ${key} ideal hit`);
    near(run[key].unsteered_probability, E.clickProbability(model, 3), 1e-12);
  }
  for (const [name, row] of Object.entries(D.variants)) {
    const m = /^click3-(steered-)?(full|memory\+last-1|memory)-r(\d)$/.exec(name);
    assert.ok(m, name);
    const ideal = E.amplifiedHistory(model, 3, { r: +m[3], reflection: m[2], steer: m[1] ? steer : null });
    near(row.ideal_probability, ideal.hit, 1e-9, `${name} ideal hit`);
  }
});

test('After-click rows: exact targets match the engine, and step-6 values match the campaign summary', () => {
  const models = { defect: E.makeModel(), no_defect: E.makeModel({ defect: false }) };
  const summary = json('hardware_campaign/runs/original_precision_v1/loop_contrasts.json').comparisons;
  const names = { plain: 'plain', local: 'steered_local', full: 'steered_full', memory: 'steered_memory' };
  for (const [build, pair] of Object.entries(D.loops.precision.builds)) {
    for (const [key, model] of Object.entries(models)) {
      const exact = E.afterClick(model, 3, 3).conditional;
      pair[key].future.forEach((f, j) => {
        near(f.exact, exact[j], 1e-12, `${build} ${key} exact`);
        near(f.probability, f.successes / f.kept);
        assert.equal(f.kept, pair[key].accepted);
      });
    }
    const step6 = summary[names[build]][2];
    assert.equal(step6.step, 6);
    near(pair.defect.future[2].probability, step6.first.probability);
    near(pair.no_defect.future[2].probability, step6.second.probability);
  }
  const local = D.loops.precision.builds.local;
  assert.equal((100 * local.defect.future[2].probability).toFixed(2), '8.79');
  assert.equal((100 * local.no_defect.future[2].probability).toFixed(2), '11.66');
});

