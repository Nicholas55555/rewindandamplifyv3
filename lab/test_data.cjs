'use strict';
/* The Lab may only show measured numbers that are in the saved hardware record.

   lab/data.js is generated by lab/make_data.py. These tests re-read the campaign's own files and confirm that
   the generated bundle still matches them, byte hashes included, and that the engine's ideal values agree with
   the ideal values the campaign stored next to each measurement.

   Run:  node --test lab/test_data.cjs
*/
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const E = require('./engine.js');
const D = require('./data.js');

const ROOT = path.join(__dirname, '..');
const json = rel => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const near = (a, b, tol = 1e-12, what = '') => assert.ok(Math.abs(a - b) <= tol, `${what} ${a} != ${b}`);

test('Every source file still has the hash recorded when the bundle was generated', () => {
  const entries = Object.entries(D.source_sha256);
  assert.ok(entries.length >= 10);
  for (const [rel, want] of entries) {
    const got = crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex');
    assert.equal(got, want, `${rel} changed: run python lab/make_data.py`);
  }
});

