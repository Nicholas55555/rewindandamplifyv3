'use strict';
/* The Lab may only show measured numbers that are in the saved hardware record.

   lab/data.js is generated by lab/make_data.py. These tests re-read the campaign's own files and confirm that
   the generated bundle still matches them, byte hashes included, and that the engine's ideal values agree with
   the ideal values the campaign stored next to each measurement.

   Run:  node --test lab/test_data.cjs
*/
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const E = require('./engine.js');
const D = require('./data.js');

const ROOT = path.join(__dirname, '..');
const json = rel => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const near = (a, b, tol = 1e-12, what = '') => assert.ok(Math.abs(a - b) <= tol, `${what} ${a} != ${b}`);

test('Every source file still has the hash recorded when the bundle was generated', () => {
  const entries = Object.entries(D.source_sha256);
  assert.ok(entries.length >= 10);
  for (const [rel, want] of entries) {
    const got = crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex');
    assert.equal(got, want, `${rel} changed: run python lab/make_data.py`);
  }
});

test('The headline pair is exactly the campaign record: 6,300 and 5,674 of 8,192', () => {
  const record = json('hardware_campaign/runs/original_precision_v1/hero_acceptance_contrast.json');
  const h = D.hero.precision;
  assert.equal(h.job_id, 'dbqb1ifv5hds73dfo310');
  assert.equal(h.local.name, record.first_name); assert.equal(h.full.name, record.second_name);
  assert.deepEqual([h.local.accepted, h.local.shots], [6300, 8192]);
  assert.deepEqual([h.full.accepted, h.full.shots], [5674, 8192]);
  assert.deepEqual([h.local.two_qubit_gates, h.full.two_qubit_gates], record.native_two_qubit_gate_counts);
  assert.deepEqual([h.local.two_qubit_gates, h.full.two_qubit_gates], [58, 125]);
  near(h.local.tv_to_exact, record.selected_history_tv_vs_unsteered[0]);
  near(h.full.tv_to_exact, record.selected_history_tv_vs_unsteered[1]);
  near(h.difference.probability, record.probability_difference);
  assert.equal((100 * h.local.probability).toFixed(2), '76.90');
  assert.equal((100 * h.full.probability).toFixed(2), '69.26');
  assert.equal(h.local.tv_to_exact.toFixed(4), '0.1177'); assert.equal(h.full.tv_to_exact.toFixed(4), '0.1814');
  assert.equal(h.local.gates_per_accepted_shot.toFixed(2), '75.42'); assert.equal(h.full.gates_per_accepted_shot.toFixed(2), '180.47');
});

test('Rates are recomputed from counts, and the accepted histories add up', () => {
  for (const run of Object.values(D.hero)) for (const key of ['local', 'full']) {
    const row = run[key];
    near(row.probability, row.accepted / row.shots);
    // histories with a click at step 3 are indices 4..7
    const hits = row.history_probabilities.slice(4).reduce((a, b) => a + b, 0);
    near(hits, row.probability, 1e-12, `${run.run} ${key}`);
    near(row.history_probabilities.reduce((a, b) => a + b, 0), 1, 1e-12);
  }
});

test('Total-variation distances can be recomputed from the measured histories and the engine', () => {
  const model = E.makeModel();
  const marked = y => ((y >> 2) & 1) === 1;
  const exact = E.conditionalDistribution(E.historyProbabilities(model, 3), marked);
  for (const run of Object.values(D.hero)) for (const key of ['local', 'full']) {
    const row = run[key];
    const measured = E.conditionalDistribution(Float64Array.from(row.history_probabilities), marked);
    near(E.totalVariation(measured, exact), row.tv_to_exact, 1e-9, `${run.run} ${key} TV`);
  }
});

test('The ideal values stored with each measurement are what the engine computes', () => {
  const model = E.makeModel(), steer = E.steerFor(model, 3);
  const kinds = { local: 'memory+last-1', full: 'full' };
  for (const run of Object.values(D.hero)) for (const [key, reflection] of Object.entries(kinds)) {
    const ideal = E.amplifiedHistory(model, 3, { r: 1, reflection, steer });
    near(run[key].ideal_probability, ideal.hit, 1e-9, `${run.run} ${key} ideal hit`);
    near(run[key].unsteered_probability, E.clickProbability(model, 3), 1e-12);
  }
  for (const [name, row] of Object.entries(D.variants)) {
    const m = /^click3-(steered-)?(full|memory\+last-1|memory)-r(\d)$/.exec(name);
    assert.ok(m, name);
    const ideal = E.amplifiedHistory(model, 3, { r: +m[3], reflection: m[2], steer: m[1] ? steer : null });
    near(row.ideal_probability, ideal.hit, 1e-9, `${name} ideal hit`);
  }
});

test('After-click rows: exact targets match the engine, and step-6 values match the campaign summary', () => {
  const models = { defect: E.makeModel(), no_defect: E.makeModel({ defect: false }) };
  const summary = json('hardware_campaign/runs/original_precision_v1/loop_contrasts.json').comparisons;
  const names = { plain: 'plain', local: 'steered_local', full: 'steered_full', memory: 'steered_memory' };
  for (const [build, pair] of Object.entries(D.loops.precision.builds)) {
    for (const [key, model] of Object.entries(models)) {
      const exact = E.afterClick(model, 3, 3).conditional;
      pair[key].future.forEach((f, j) => {
        near(f.exact, exact[j], 1e-12, `${build} ${key} exact`);
        near(f.probability, f.successes / f.kept);
        assert.equal(f.kept, pair[key].accepted);
      });
    }
    const step6 = summary[names[build]][2];
    assert.equal(step6.step, 6);
    near(pair.defect.future[2].probability, step6.first.probability);
    near(pair.no_defect.future[2].probability, step6.second.probability);
  }
  const local = D.loops.precision.builds.local;
  assert.equal((100 * local.defect.future[2].probability).toFixed(2), '8.79');
  assert.equal((100 * local.no_defect.future[2].probability).toFixed(2), '11.66');
});

test('Campaign totals and job list match the campaign summary', () => {
  const summary = json('hardware_campaign/results.json');
  assert.equal(D.backend, 'ibm_marrakesh');
  assert.equal(D.campaign.jobs, summary.jobs); assert.equal(D.jobs.length, 10);
  assert.equal(D.campaign.total_shots, 688640); assert.equal(D.campaign.qpu_seconds, 244);
  assert.equal(D.jobs.reduce((s, j) => s + j.qpu_seconds, 0), D.campaign.qpu_seconds);
  assert.equal(D.jobs.reduce((s, j) => s + (j.science_circuits + j.calibration_circuits) * j.shots_per_circuit, 0), D.campaign.total_shots);
  for (const run of Object.values(D.hero)) assert.ok(D.jobs.some(j => j.job_id === run.job_id));
});

test('The single-file Lab embeds exactly the current sources', () => {
  const single = path.join(ROOT, 'Rewind_Amplify_Lab.html');
  if (!fs.existsSync(single)) return;       // not built yet in a fresh checkout before lab/build.py runs
  const html = fs.readFileSync(single, 'utf8');
  for (const name of ['engine.js', 'data.js', 'app.js', 'styles.css']) {
    const source = fs.readFileSync(path.join(__dirname, name), 'utf8').replace(/\r\n/g, '\n').replace(/<\/script/gi, '<\\/script');
    assert.ok(html.includes(source), `${name} is stale in Rewind_Amplify_Lab.html: run python lab/build.py`);
  }
  assert.ok(!/<script[^>]+src=/.test(html));
});
