"""Stronger evaluation: match the no-defect click rate, then test held-out likelihood."""
import argparse
from dataclasses import replace
import hashlib
import json
from pathlib import Path
import numpy as np
from scipy.optimize import minimize_scalar
from qrsm_photon import Parameters, instruments, init_state, _traces, fit_coupling, record_loglikelihood

ROOT=Path(__file__).resolve().parent

def click_rate(p, total_bins=90, skip=45):
    no,yes,full=instruments(p)
    dim=4*p.n_cavity
    vec=init_state(p)[:,None]
    probs=[]
    for i in range(total_bins):
        hit=_traces(yes@vec,dim)[0]
        if i>=skip: probs.append(hit)
        vec=full@vec
    return float(np.mean(probs))

def run(data_dir=ROOT/'generated', out_dir=None, overwrite=False):
    p=Parameters()
    data_dir=Path(data_dir).expanduser().resolve()
    out_dir=Path(out_dir if out_dir is not None else data_dir).expanduser().resolve()
    if out_dir == ROOT:
        raise ValueError('Evaluation output must be separate from the bundled reference files')
    data_path=data_dir/'synthetic_click_records.csv'
    output_path=out_dir/'heldout_evaluation.json'
    if output_path.exists() and not overwrite:
        raise FileExistsError(f'{output_path} exists; choose another --outdir or pass --overwrite')
    if not data_path.is_file():
        raise FileNotFoundError(f'No input records at {data_path}; run experiment.py first')
    recs=np.loadtxt(data_path,delimiter=',',dtype=float,ndmin=2)
    if recs.shape[0] < 4 or recs.shape[1] < 2 or not np.all((recs==0)|(recs==1)):
        raise ValueError('Input must contain at least four binary records with at least two bins each')
    recs=recs.astype(np.uint8)
    ntrain=int(len(recs)*.7)
    train,test=recs[:ntrain],recs[ntrain:]
    fit=fit_coupling(train,p,np.linspace(0,1.25,26))
    target=float(train.mean())
    def err(drive):
        return (click_rate(replace(p,g_defect=0,drive=drive))-target)**2
    opt=minimize_scalar(err,bounds=(0.2,2.3),method='bounded',options={'xatol':1e-4})
    null=replace(p,g_defect=0,drive=float(opt.x))
    chosen=replace(p,g_defect=fit['g_hat'])
    ll_true=record_loglikelihood(test,chosen)
    ll_null=record_loglikelihood(test,null)
    # Include a trivial independent Bernoulli baseline, with training-rate fit.
    n1=int(test.sum()); nt=int(test.size)
    ll_iid=n1*np.log(np.clip(target,1e-9,1))+(nt-n1)*np.log(np.clip(1-target,1e-9,1))
    # First-order Markov baseline fitted on training records with Laplace smoothing.
    counts=np.ones((2,2))
    for r in train:
        for a,b in zip(r[:-1],r[1:]): counts[a,b]+=1
    tr=counts/counts.sum(axis=1,keepdims=True)
    init=np.array([(train[:,0]==0).sum()+1,(train[:,0]==1).sum()+1],float)
    init/=init.sum()
    ll_markov=sum(np.log(init[int(r[0])])+sum(np.log(tr[a,b]) for a,b in zip(r[:-1],r[1:])) for r in test)
    result={
      'input_records_sha256':hashlib.sha256(data_path.read_bytes()).hexdigest(),
      'n_train_records':ntrain,'n_test_records':len(test),'steps_per_record':recs.shape[1],
      'g_hat_train':fit['g_hat'],'g_true':p.g_defect,
      'train_photon_click_rate':target,
      'rate_matched_null_drive':float(opt.x),
      'rate_matched_null_predicted_rate':click_rate(null),
      'heldout_loglik_qrsm':ll_true,
      'heldout_loglik_rate_matched_no_defect':ll_null,
      'heldout_delta_lnL_vs_rate_matched_no_defect':ll_true-ll_null,
      'heldout_loglik_iid':float(ll_iid),
      'heldout_loglik_markov1':float(ll_markov),
      'heldout_delta_lnL_vs_markov1':ll_true-ll_markov,
      'note':'Synthetic data generated by same known family; nuisance parameters fixed for QRSM, null drive adjusted to mean; Markov/IID are baselines not exhaustive.'
    }
    out_dir.mkdir(parents=True,exist_ok=True)
    output_path.write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(result,indent=2))
    return result

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir',type=Path,default=ROOT/'generated',help='directory containing synthetic_click_records.csv')
    parser.add_argument('--outdir',type=Path,help='evaluation output directory (default: data directory)')
    parser.add_argument('--overwrite',action='store_true',help='replace a previous evaluation in the output directory')
    args=parser.parse_args()
    run(data_dir=args.data_dir,out_dir=args.outdir,overwrite=args.overwrite)
